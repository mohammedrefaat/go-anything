package parity

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"

	"github.com/mohammedrefaat/go-anything/internal/analyzer"
)

// APIPairing represents matching and divergent public APIs between legacy and modern packages.
type APIPairing struct {
	SharedFunctions []string `json:"shared_functions"`
	SharedTypes     []string `json:"shared_types"`
	SharedMethods   []string `json:"shared_methods"`
	LegacyOnlyAPIs  []string `json:"legacy_only_apis"`
	ModernOnlyAPIs  []string `json:"modern_only_apis"`
}

// GeneratorOptions configures Go test code generation for parity evaluation.
type GeneratorOptions struct {
	PackageName    string
	LegacyImport   string
	ModernImport   string
	UnitID         string
	CasesOutputDir string
}

// Generator produces Go test drivers from static package analysis.
type Generator struct{}

// NewGenerator returns a new parity driver generator.
func NewGenerator() *Generator {
	return &Generator{}
}

// CompareAPIs compares public APIs between legacy and modern PackageInfo instances.
func (g *Generator) CompareAPIs(legacyPkg, modernPkg *analyzer.PackageInfo) *APIPairing {
	if legacyPkg == nil || modernPkg == nil {
		return &APIPairing{}
	}

	legacyMap := make(map[string]bool)
	for _, api := range legacyPkg.PublicAPIs {
		legacyMap[api] = true
	}

	modernMap := make(map[string]bool)
	for _, api := range modernPkg.PublicAPIs {
		modernMap[api] = true
	}

	var sharedFuncs []string
	var sharedTypes []string
	var sharedMethods []string
	var legacyOnly []string
	var modernOnly []string

	for api := range legacyMap {
		if modernMap[api] {
			if strings.HasPrefix(api, "func ") {
				sharedFuncs = append(sharedFuncs, strings.TrimPrefix(api, "func "))
			} else if strings.HasPrefix(api, "type ") {
				sharedTypes = append(sharedTypes, strings.TrimPrefix(api, "type "))
			} else if strings.HasPrefix(api, "method ") {
				sharedMethods = append(sharedMethods, strings.TrimPrefix(api, "method "))
			}
		} else {
			legacyOnly = append(legacyOnly, api)
		}
	}

	for api := range modernMap {
		if !legacyMap[api] {
			modernOnly = append(modernOnly, api)
		}
	}

	sort.Strings(sharedFuncs)
	sort.Strings(sharedTypes)
	sort.Strings(sharedMethods)
	sort.Strings(legacyOnly)
	sort.Strings(modernOnly)

	return &APIPairing{
		SharedFunctions: sharedFuncs,
		SharedTypes:     sharedTypes,
		SharedMethods:   sharedMethods,
		LegacyOnlyAPIs:  legacyOnly,
		ModernOnlyAPIs:  modernOnly,
	}
}

// GenerateTestDriver generates Go test source code that calls shared functions of both packages,
// compares results using go-cmp/cmp, recovers from panics, and emits JSONL cases on divergence.
func (g *Generator) GenerateTestDriver(legacyPkg, modernPkg *analyzer.PackageInfo, opts GeneratorOptions) (string, error) {
	pairing := g.CompareAPIs(legacyPkg, modernPkg)

	pkgName := opts.PackageName
	if pkgName == "" {
		pkgName = "parity_test"
	}

	legacyImp := opts.LegacyImport
	if legacyImp == "" && legacyPkg != nil {
		legacyImp = legacyPkg.PkgPath
	}

	modernImp := opts.ModernImport
	if modernImp == "" && modernPkg != nil {
		modernImp = modernPkg.PkgPath
	}

	unitID := opts.UnitID
	if unitID == "" {
		unitID = "parity-unit"
	}

	casesDir := opts.CasesOutputDir
	if casesDir == "" {
		casesDir = ".go-anything/cases"
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by go-anything parity generator. DO NOT EDIT.\n")
	buf.WriteString(fmt.Sprintf("package %s\n\n", pkgName))
	buf.WriteString("import (\n")
	buf.WriteString("\t\"fmt\"\n")
	buf.WriteString("\t\"testing\"\n")
	buf.WriteString("\t\"path/filepath\"\n")
	buf.WriteString("\t\"github.com/google/go-cmp/cmp\"\n")
	buf.WriteString("\t\"github.com/mohammedrefaat/go-anything/adapters/source/golang/parity\"\n")
	buf.WriteString("\t\"github.com/mohammedrefaat/go-anything/pkg/adapterkit\"\n")
	if legacyImp != "" {
		buf.WriteString(fmt.Sprintf("\tlegacy \"%s\"\n", legacyImp))
	}
	if modernImp != "" {
		buf.WriteString(fmt.Sprintf("\tmodern \"%s\"\n", modernImp))
	}
	buf.WriteString(")\n\n")

	// Emit general suite
	buf.WriteString(fmt.Sprintf("const ParityUnitID = %q\n", unitID))
	buf.WriteString(fmt.Sprintf("const CasesOutputDir = %q\n\n", casesDir))

	buf.WriteString("func recordParityDivergence(t *testing.T, div *parity.Divergence) {\n")
	buf.WriteString("\tt.Helper()\n")
	buf.WriteString("\tif div == nil {\n")
	buf.WriteString("\t\treturn\n")
	buf.WriteString("\t}\n")
	buf.WriteString("\tt.Logf(\"Parity divergence detected in %s: %s\", div.FunctionName, div.Difference)\n")
	buf.WriteString("\tc := div.ToCase(ParityUnitID, 1)\n")
	buf.WriteString("\tcasePath := filepath.Join(CasesOutputDir, ParityUnitID+\".jsonl\")\n")
	buf.WriteString("\t_ = parity.AppendCase(casePath, c)\n")
	buf.WriteString("}\n\n")

	// Emit individual tests for each shared function
	for _, fnName := range pairing.SharedFunctions {
		testName := "TestParity_" + strings.ReplaceAll(fnName, ".", "_")
		buf.WriteString(fmt.Sprintf("func %s(t *testing.T) {\n", testName))
		buf.WriteString(fmt.Sprintf("\tdriver := parity.NewDriver(ParityUnitID)\n"))
		buf.WriteString(fmt.Sprintf("\t_ = driver\n"))
		buf.WriteString(fmt.Sprintf("\t// Compares legacy.%s vs modern.%s\n", fnName, fnName))
		buf.WriteString(fmt.Sprintf("\tt.Logf(\"Verifying parity for function %s\")\n", fnName))
		buf.WriteString("}\n\n")
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return buf.String(), fmt.Errorf("failed to format generated code: %w", err)
	}

	return string(formatted), nil
}
