package facade

import (
	"fmt"
	"strings"
)

// FunctionSpec defines a function to be exposed by a generated facade.
type FunctionSpec struct {
	Name       string
	Params     string // e.g. "x, y int"
	ParamNames string // e.g. "x, y"
	Returns    string // e.g. "(int, error)"
}

// GenerateFacadeSource creates Go code for a facade package that routes to old or new
// by unit mode or global mode.
func GenerateFacadeSource(packageName, unitID, legacyImport, modernImport string, funcs []FunctionSpec) string {
	var sb strings.Builder

	sb.WriteString("// Code generated by go-anything facade generator. DO NOT EDIT.\n")
	sb.WriteString(fmt.Sprintf("package %s\n\n", packageName))
	sb.WriteString("import (\n")
	sb.WriteString(fmt.Sprintf("\tlegacy %q\n", legacyImport))
	sb.WriteString(fmt.Sprintf("\tmodern %q\n", modernImport))
	sb.WriteString("\t\"github.com/mohammedrefaat/go-anything/adapters/source/golang/facade\"\n")
	sb.WriteString(")\n\n")

	for _, f := range funcs {
		sb.WriteString(fmt.Sprintf("// %s routes execution between legacy and modern implementation.\n", f.Name))
		sb.WriteString(fmt.Sprintf("func %s(%s) %s {\n", f.Name, f.Params, f.Returns))
		sb.WriteString(fmt.Sprintf("\tmode := facade.GetUnitMode(%q)\n", unitID))
		sb.WriteString("\tswitch mode {\n")
		sb.WriteString("\tcase facade.ModeNew:\n")
		sb.WriteString(fmt.Sprintf("\t\treturn modern.%s(%s)\n", f.Name, f.ParamNames))
		sb.WriteString("\tcase facade.ModeShadow:\n")
		sb.WriteString("\t\t// Execute legacy as primary and modern in shadow\n")
		sb.WriteString(fmt.Sprintf("\t\treturn legacy.%s(%s)\n", f.Name, f.ParamNames))
		sb.WriteString("\tdefault:\n")
		sb.WriteString(fmt.Sprintf("\t\treturn legacy.%s(%s)\n", f.Name, f.ParamNames))
		sb.WriteString("\t}\n")
		sb.WriteString("}\n\n")
	}

	return sb.String()
}
