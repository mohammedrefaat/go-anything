func TestCLI_Bridge_Help(t *testing.T) {
	var stdout, stderr bytes.Buffer
	err := runCLI([]string{"bridge", "--help"}, &stdout, &stderr)
	require.NoError(t, err)

	out := stdout.String()
	assert.Contains(t, out, "Usage:")
	assert.Contains(t, out, "go-anything bridge")
	assert.Contains(t, out, "--unit, -u")
	assert.Contains(t, out, "--function, -f")
	assert.Contains(t, out, "--transport, -t")
	assert.Contains(t, out, "--dir, -d")
	assert.Contains(t, out, "--json")
	assert.Contains(t, out, "Exit Codes:")
	assert.Contains(t, out, "0   Success / OK")
	assert.Contains(t, out, "2   Usage error")
	assert.Contains(t, out, "3   Internal code generation error")
}

func TestCLI_Bridge_FlagsValidation(t *testing.T) {
	var stdout, stderr bytes.Buffer
	err := runCLI([]string{"bridge"}, &stdout, &stderr)
	require.Error(t, err)
	assert.Equal(t, ExitCodeUsage, GetExitCode(err))
	assert.Contains(t, err.Error(), "flag --unit (-u) is required")
}

func setupBridgeWorkspace(t *testing.T, unitID string) string {
	tempDir := t.TempDir()

	dotDir := filepath.Join(tempDir, ".go-anything")
	require.NoError(t, os.MkdirAll(dotDir, 0755))

	manifest := adapterkit.Manifest{
		SchemaVersion:  adapterkit.SchemaVersionV1,
		ProjectName:    "bridge-test-ws",
		SourceLanguage: "python",
		TargetLanguage: "go",
		Units:          []string{unitID},
	}
	mData, err := json.Marshal(manifest)
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(filepath.Join(dotDir, "manifest.json"), mData, 0644))

	return tempDir
}

func TestCLI_Bridge_Compile_Lifecycle_And_Idempotence(t *testing.T) {
	unitID := "pkg/billing"
	wsDir := setupBridgeWorkspace(t, unitID)

	// Step 1: Write a custom bridge.yaml in workspace root
	manifestContent := `
version: "v1alpha1"
unit: "pkg/billing"
service: "billing-bridge"
transport:
  default: "stdio"
functions:
  - name: "calculate_tax"
    description: "Computes sales tax."
    idempotent: true
    timeout_ms: 2000
    params:
      - name: "amount"
        type: "float64"
        required: true
      - name: "currency"
        type: "string"
        required: true
    returns:
      type: "object"
      properties:
        tax_amount: "float64"
        currency: "string"
    errors:
      - code: -32001
        name: "UnsupportedCurrencyError"
        description: "Currency not supported"
`
	manifestPath := filepath.Join(wsDir, "bridge.yaml")
	require.NoError(t, os.WriteFile(manifestPath, []byte(manifestContent), 0644))

	outSidecarDir := filepath.Join(wsDir, "bridges", "pkg", "billing")

	// Step 2: Run CLI bridge command with --json
	var stdout, stderr bytes.Buffer
	err := runCLI([]string{
		"bridge",
		"--unit=" + unitID,
		"--manifest=" + manifestPath,
		"--out=" + outSidecarDir,
		"--dir=" + wsDir,
		"--json",
	}, &stdout, &stderr)

	require.NoError(t, err, "stderr: %s", stderr.String())

	var genRes bridge.GenerateResult
	require.NoError(t, json.Unmarshal(stdout.Bytes(), &genRes))
	assert.Equal(t, outSidecarDir, genRes.OutputDir)
	assert.Contains(t, genRes.GeneratedFiles, "main.go")
	assert.Contains(t, genRes.GeneratedFiles, "types.go")
	assert.Contains(t, genRes.GeneratedFiles, "handlers.go")
	assert.Contains(t, genRes.GeneratedFiles, "handlers_impl.go")
	assert.Contains(t, genRes.GeneratedFiles, "bridge_test.go")
	assert.Contains(t, genRes.GeneratedFiles, "wrapper.py")
	assert.Contains(t, genRes.GeneratedFiles, "wrapper.ts")

	// Verify headers on generated files
	for _, f := range genRes.GeneratedFiles {
		fullPath := filepath.Join(outSidecarDir, f)
		assert.FileExists(t, fullPath)
		content, err := os.ReadFile(fullPath)
		require.NoError(t, err)

		if strings.HasSuffix(f, ".go") && f != "handlers_impl.go" {
			assert.Contains(t, string(content), "// Code generated by go-anything bridge; DO NOT EDIT.")
		}
		if f == "handlers_impl.go" {
			assert.Contains(t, string(content), "// TODO(port)")
			assert.Contains(t, string(content), "ErrNotPorted")
		}
		if strings.HasSuffix(f, ".py") {
			assert.Contains(t, string(content), "# Code generated by go-anything bridge; DO NOT EDIT.")
		}
		if strings.HasSuffix(f, ".ts") {
			assert.Contains(t, string(content), "// Code generated by go-anything bridge; DO NOT EDIT.")
		}
	}

	// -------------------------------------------------------------------------
	// Step 3: Compile Test
	// Runs `go build` in temp directory on the generated sidecar, asserting it compiles cleanly.
	// -------------------------------------------------------------------------
	t.Run("compile_generated_sidecar", func(t *testing.T) {
		binName := "sidecar"
		if os.PathSeparator == '\\' {
			binName += ".exe"
		}
		binPath := filepath.Join(outSidecarDir, binName)

		buildCmd := exec.Command("go", "build", "-o", binPath, "main.go", "types.go", "handlers.go", "handlers_impl.go")
		buildCmd.Dir = outSidecarDir
		buildOut, err := buildCmd.CombinedOutput()
		require.NoError(t, err, "sidecar must compile cleanly: %s", string(buildOut))
		assert.FileExists(t, binPath)
	})

	// -------------------------------------------------------------------------
	// Step 4: Lifecycle Test
	// Spawns the compiled sidecar binary, sends `ping` and `hello` JSON-RPC requests
	// via stdin, and asserts valid responses.
	// -------------------------------------------------------------------------
	t.Run("lifecycle_ping_and_hello", func(t *testing.T) {
		binName := "sidecar"
		if os.PathSeparator == '\\' {
			binName += ".exe"
		}
		binPath := filepath.Join(outSidecarDir, binName)

		sidecarCmd := exec.Command(binPath)
		sidecarCmd.Dir = outSidecarDir

		stdinPipe, err := sidecarCmd.StdinPipe()
		require.NoError(t, err)

		stdoutPipe, err := sidecarCmd.StdoutPipe()
		require.NoError(t, err)

		require.NoError(t, sidecarCmd.Start())

		defer func() {
			if sidecarCmd.Process != nil {
				_ = sidecarCmd.Process.Kill()
			}
		}()

		reader := bufio.NewReader(stdoutPipe)

		// 1. Send "hello" handshake
		helloReq := map[string]any{
			"jsonrpc": "2.0",
			"id":      1,
			"method":  "hello",
			"params":  map[string]any{},
		}
		require.NoError(t, sendLSPRequest(stdinPipe, helloReq))

		helloBytes, err := readLSPResponseWithTimeout(reader, 5*time.Second)
		require.NoError(t, err)

		var helloResp struct {
			JSONRPC string `json:"jsonrpc"`
			ID      int    `json:"id"`
			Result  struct {
				Status    string   `json:"status"`
				Protocol  int      `json:"protocol"`
				Unit      string   `json:"unit"`
				Service   string   `json:"service"`
				Functions []string `json:"functions"`
				PID       int      `json:"pid"`
			} `json:"result"`
		}
		require.NoError(t, json.Unmarshal(helloBytes, &helloResp))
		assert.Equal(t, 1, helloResp.ID)
		assert.Equal(t, "ready", helloResp.Result.Status)
		assert.Equal(t, 1, helloResp.Result.Protocol)
		assert.Equal(t, "pkg/billing", helloResp.Result.Unit)
		assert.Equal(t, "billing-bridge", helloResp.Result.Service)
		assert.Contains(t, helloResp.Result.Functions, "calculate_tax")
		assert.Greater(t, helloResp.Result.PID, 0)

		// 2. Send "ping" health check
		pingReq := map[string]any{
			"jsonrpc": "2.0",
			"id":      2,
			"method":  "ping",
			"params":  map[string]any{},
		}
		require.NoError(t, sendLSPRequest(stdinPipe, pingReq))

		pingBytes, err := readLSPResponseWithTimeout(reader, 5*time.Second)
		require.NoError(t, err)

		var pingResp struct {
			JSONRPC string `json:"jsonrpc"`
			ID      int    `json:"id"`
			Result  struct {
				Status string `json:"status"`
				Time   string `json:"time"`
			} `json:"result"`
		}
		require.NoError(t, json.Unmarshal(pingBytes, &pingResp))
		assert.Equal(t, 2, pingResp.ID)
		assert.Equal(t, "pong", pingResp.Result.Status)
		assert.NotEmpty(t, pingResp.Result.Time)

		// 3. Send "shutdown"
		shutdownReq := map[string]any{
			"jsonrpc": "2.0",
			"id":      3,
			"method":  "shutdown",
			"params":  map[string]any{},
		}
		require.NoError(t, sendLSPRequest(stdinPipe, shutdownReq))

		shutdownBytes, err := readLSPResponseWithTimeout(reader, 5*time.Second)
		require.NoError(t, err)

		var shutdownResp struct {
			ID     int            `json:"id"`
			Result map[string]any `json:"result"`
		}
		require.NoError(t, json.Unmarshal(shutdownBytes, &shutdownResp))
		assert.Equal(t, 3, shutdownResp.ID)
		assert.Equal(t, "ok", shutdownResp.Result["status"])

		// Confirm clean exit
		_ = stdinPipe.Close()
		waitErr := sidecarCmd.Wait()
		require.NoError(t, waitErr)
	})

	// -------------------------------------------------------------------------
	// Step 5: Idempotence Test
	// Modifies `handlers_impl.go` with a custom comment or code, runs `bridge`
	// command again, and asserts `handlers_impl.go` is preserved untouched.
	// -------------------------------------------------------------------------
	t.Run("idempotent_preserves_handlers_impl", func(t *testing.T) {
		implPath := filepath.Join(outSidecarDir, "handlers_impl.go")
		customCode := "\n// CUSTOM_DEVELOPER_IMPLEMENTATION_TOKEN_ABC123456\n"
		f, err := os.OpenFile(implPath, os.O_APPEND|os.O_WRONLY, 0644)
		require.NoError(t, err)
		_, err = f.WriteString(customCode)
		require.NoError(t, err)
		f.Close()

		// Re-run bridge command
		stdout.Reset()
		stderr.Reset()
		err = runCLI([]string{
			"bridge",
			"--unit=" + unitID,
			"--manifest=" + manifestPath,
			"--out=" + outSidecarDir,
			"--dir=" + wsDir,
		}, &stdout, &stderr)

		require.NoError(t, err, "stderr: %s", stderr.String())

		outText := stdout.String()
		assert.Contains(t, outText, "Preserved Existing Files (1):")
		assert.Contains(t, outText, "handlers_impl.go")

		// Confirm custom implementation was preserved
		preservedContent, err := os.ReadFile(implPath)
		require.NoError(t, err)
		assert.Contains(t, string(preservedContent), "CUSTOM_DEVELOPER_IMPLEMENTATION_TOKEN_ABC123456",
			"handlers_impl.go must NOT be overwritten on regeneration (Rule R-2)")
	})
}

func sendLSPRequest(w io.Writer, req any) error {
	data, err := json.Marshal(req)
	if err != nil {
		return err
	}
	header := fmt.Sprintf("Content-Length: %d\r\n\r\n", len(data))
	if _, err := io.WriteString(w, header); err != nil {
		return err
	}
	_, err = w.Write(data)
	return err
}

func readLSPResponseWithTimeout(r *bufio.Reader, timeout time.Duration) ([]byte, error) {
	type readResult struct {
		data []byte
		err  error
	}

	ch := make(chan readResult, 1)
	go func() {
		contentLength := -1
		for {
			line, err := r.ReadString('\n')
			if err != nil {
				ch <- readResult{nil, err}
				return
			}
			line = strings.TrimRight(line, "\r\n")
			if line == "" {
				break
			}
			lower := strings.ToLower(line)
			if strings.HasPrefix(lower, "content-length:") {
				parts := strings.SplitN(line, ":", 2)
				if len(parts) == 2 {
					val, err := strconv.Atoi(strings.TrimSpace(parts[1]))
					if err == nil {
						contentLength = val
					}
				}
			}
		}

		if contentLength < 0 {
			ch <- readResult{nil, fmt.Errorf("missing Content-Length in response")}
			return
		}

		buf := make([]byte, contentLength)
		if _, err := io.ReadFull(r, buf); err != nil {
			ch <- readResult{nil, err}
			return
		}

		ch <- readResult{buf, nil}
	}()

	select {
	case res := <-ch:
		return res.data, res.err
	case <-time.After(timeout):
		return nil, fmt.Errorf("read timeout waiting for sidecar response")
	}
}
