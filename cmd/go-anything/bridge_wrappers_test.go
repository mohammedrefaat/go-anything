func TestBridgeWrappers_Generation(t *testing.T) {
	unitID := "pkg/billing"
	wsDir := setupBridgeWorkspace(t, unitID)

	manifestContent := `
version: "v1alpha1"
unit: "pkg/billing"
service: "billing-bridge"
transport:
  default: "stdio"
functions:
  - name: "calculate_tax"
    description: "Computes sales tax."
    idempotent: true
    timeout_ms: 2000
    params:
      - name: "amount"
        type: "float64"
        required: true
      - name: "currency"
        type: "string"
        required: true
    returns:
      type: "object"
      properties:
        tax_amount: "float64"
        currency: "string"
`
	manifestPath := filepath.Join(wsDir, "bridge.yaml")
	require.NoError(t, os.WriteFile(manifestPath, []byte(manifestContent), 0644))

	outDir := filepath.Join(wsDir, "bridges", "pkg", "billing")

	var stdout, stderr bytes.Buffer
	err := runCLI([]string{
		"bridge",
		"--unit=" + unitID,
		"--manifest=" + manifestPath,
		"--out=" + outDir,
		"--dir=" + wsDir,
	}, &stdout, &stderr)

	require.NoError(t, err, "stderr: %s", stderr.String())

	// Verify wrappers directory files
	pyWrapper := filepath.Join(outDir, "wrappers", "bridge.py")
	tsWrapper := filepath.Join(outDir, "wrappers", "bridge.ts")
	dtsWrapper := filepath.Join(outDir, "wrappers", "bridge.d.ts")

	assert.FileExists(t, pyWrapper)
	assert.FileExists(t, tsWrapper)
	assert.FileExists(t, dtsWrapper)

	pyContent, err := os.ReadFile(pyWrapper)
	require.NoError(t, err)
	assert.Contains(t, string(pyContent), "# Code generated by go-anything bridge; DO NOT EDIT.")
	assert.Contains(t, string(pyContent), "BillingBridgeClient")
	assert.Contains(t, string(pyContent), "def calculate_tax")
	assert.Contains(t, string(pyContent), "_original_calculate_tax")
	assert.Contains(t, string(pyContent), "GO_ANYTHING_BRIDGE")

	tsContent, err := os.ReadFile(tsWrapper)
	require.NoError(t, err)
	assert.Contains(t, string(tsContent), "// Code generated by go-anything bridge; DO NOT EDIT.")
	assert.Contains(t, string(tsContent), "BillingBridgeClient")
	assert.Contains(t, string(tsContent), "calculateTax")
	assert.Contains(t, string(tsContent), "_original_calculate_tax")
	assert.Contains(t, string(tsContent), "GO_ANYTHING_BRIDGE")

	dtsContent, err := os.ReadFile(dtsWrapper)
	require.NoError(t, err)
	assert.Contains(t, string(dtsContent), "// Code generated by go-anything bridge; DO NOT EDIT.")
	assert.Contains(t, string(dtsContent), "export interface CalculateTaxParams")
}

func TestBridgeWrappers_PythonIntegration(t *testing.T) {
	unitID := "pkg/billing"
	wsDir := setupBridgeWorkspace(t, unitID)

	manifestContent := `
version: "v1alpha1"
unit: "pkg/billing"
service: "billing-bridge"
transport:
  default: "stdio"
functions:
  - name: "calculate_tax"
    description: "Computes sales tax."
    idempotent: true
    timeout_ms: 2000
    params:
      - name: "amount"
        type: "float64"
        required: true
      - name: "currency"
        type: "string"
        required: true
    returns:
      type: "object"
      properties:
        tax_amount: "float64"
        currency: "string"
`
	manifestPath := filepath.Join(wsDir, "bridge.yaml")
	require.NoError(t, os.WriteFile(manifestPath, []byte(manifestContent), 0644))

	outDir := filepath.Join(wsDir, "bridges", "pkg", "billing")

	var stdout, stderr bytes.Buffer
	err := runCLI([]string{
		"bridge",
		"--unit=" + unitID,
		"--manifest=" + manifestPath,
		"--out=" + outDir,
		"--dir=" + wsDir,
	}, &stdout, &stderr)
	require.NoError(t, err, "stderr: %s", stderr.String())

	// Replace handlers_impl.go with an actual working implementation
	workingImpl := `package main

import (
	"context"
	"errors"
)

var ErrNotPorted = errors.New("ErrNotPorted")

type HandlersImpl struct{}

func NewHandlers() Handlers {
	return &HandlersImpl{}
}

func (h *HandlersImpl) CalculateTax(ctx context.Context, req *CalculateTaxRequest) (*CalculateTaxResponse, error) {
	return &CalculateTaxResponse{
		TaxAmount: req.Amount * 0.15,
		Currency:  req.Currency,
	}, nil
}
`
	implPath := filepath.Join(outDir, "handlers_impl.go")
	require.NoError(t, os.WriteFile(implPath, []byte(workingImpl), 0644))

	// Compile sidecar binary
	binName := "sidecar"
	if os.PathSeparator == '\\' {
		binName += ".exe"
	}
	binPath := filepath.Join(outDir, binName)

	buildCmd := exec.Command("go", "build", "-o", binPath, "main.go", "types.go", "handlers.go", "handlers_impl.go")
	buildCmd.Dir = outDir
	buildOut, err := buildCmd.CombinedOutput()
	require.NoError(t, err, "sidecar compilation failed: %s", string(buildOut))

	// Create test python script to execute against the bridge wrapper
	pyTestScript := fmt.Sprintf(`
import os
import sys

# Add wrappers directory to sys.path
wrappers_dir = os.path.abspath(r"%s")
sys.path.insert(0, wrappers_dir)

import bridge

os.environ["GO_ANYTHING_BRIDGE_BIN"] = r"%s"

client = bridge.get_client()

# 1. Normal execution through Go sidecar
res1 = bridge.calculate_tax(amount=100.0, currency="USD")
print(f"RES1: {res1}")
assert abs(res1["tax_amount"] - 15.0) < 1e-6, f"Expected 15.0, got {res1}"
assert res1["currency"] == "USD"

# 2. Kill-switch test: GO_ANYTHING_BRIDGE=off should route to original function
os.environ["GO_ANYTHING_BRIDGE"] = "off"
bridge._original_calculate_tax = lambda amount=None, currency=None, **kw: {"tax_amount": 99.0, "currency": "FALLBACK"}
res2 = bridge.calculate_tax(amount=100.0, currency="USD")
print(f"RES2: {res2}")
assert res2["tax_amount"] == 99.0, f"Expected fallback 99.0, got {res2}"
assert res2["currency"] == "FALLBACK"

# 3. Process kill resilience test
os.environ["GO_ANYTHING_BRIDGE"] = "on"
# Deliberately kill child process mid-run
if client._process is not None:
    client._process.kill()
    client._process.wait()

# Next call must cleanly restart sidecar and succeed without deadlock or hanging
res3 = bridge.calculate_tax(amount=200.0, currency="EUR")
print(f"RES3: {res3}")
assert abs(res3["tax_amount"] - 30.0) < 1e-6, f"Expected 30.0, got {res3}"
assert res3["currency"] == "EUR"

client.close()
print("PYTHON_TEST_SUCCESS")
`, filepath.Join(outDir, "wrappers"), binPath)

	pyScriptPath := filepath.Join(wsDir, "test_wrapper.py")
	require.NoError(t, os.WriteFile(pyScriptPath, []byte(pyTestScript), 0644))

	pyCmd := exec.Command("python", pyScriptPath)
	pyCmd.Dir = wsDir
	pyOut, err := pyCmd.CombinedOutput()
	require.NoError(t, err, "python wrapper test failed: %s", string(pyOut))
	assert.Contains(t, string(pyOut), "PYTHON_TEST_SUCCESS")
}

func TestBridgeWrappers_TypeScriptIntegration(t *testing.T) {
	unitID := "pkg/billing"
	wsDir := setupBridgeWorkspace(t, unitID)

	manifestContent := `
version: "v1alpha1"
unit: "pkg/billing"
service: "billing-bridge"
transport:
  default: "stdio"
functions:
  - name: "calculate_tax"
    description: "Computes sales tax."
    idempotent: true
    timeout_ms: 2000
    params:
      - name: "amount"
        type: "float64"
        required: true
      - name: "currency"
        type: "string"
        required: true
    returns:
      type: "object"
      properties:
        tax_amount: "float64"
        currency: "string"
`
	manifestPath := filepath.Join(wsDir, "bridge.yaml")
	require.NoError(t, os.WriteFile(manifestPath, []byte(manifestContent), 0644))

	outDir := filepath.Join(wsDir, "bridges", "pkg", "billing")

	var stdout, stderr bytes.Buffer
	err := runCLI([]string{
		"bridge",
		"--unit=" + unitID,
		"--manifest=" + manifestPath,
		"--out=" + outDir,
		"--dir=" + wsDir,
	}, &stdout, &stderr)
	require.NoError(t, err, "stderr: %s", stderr.String())

	// Replace handlers_impl.go with an actual working implementation
	workingImpl := `package main

import (
	"context"
	"errors"
)

var ErrNotPorted = errors.New("ErrNotPorted")

type HandlersImpl struct{}

func NewHandlers() Handlers {
	return &HandlersImpl{}
}

func (h *HandlersImpl) CalculateTax(ctx context.Context, req *CalculateTaxRequest) (*CalculateTaxResponse, error) {
	return &CalculateTaxResponse{
		TaxAmount: req.Amount * 0.20,
		Currency:  req.Currency,
	}, nil
}
`
	implPath := filepath.Join(outDir, "handlers_impl.go")
	require.NoError(t, os.WriteFile(implPath, []byte(workingImpl), 0644))

	// Compile sidecar binary
	binName := "sidecar"
	if os.PathSeparator == '\\' {
		binName += ".exe"
	}
	binPath := filepath.Join(outDir, binName)

	buildCmd := exec.Command("go", "build", "-o", binPath, "main.go", "types.go", "handlers.go", "handlers_impl.go")
	buildCmd.Dir = outDir
	buildOut, err := buildCmd.CombinedOutput()
	require.NoError(t, err, "sidecar compilation failed: %s", string(buildOut))

	// Create test script for TypeScript client wrapper running on Node.js
	escapedBinPath := strings.ReplaceAll(binPath, "\\", "\\\\")
	escapedWrapperPath := strings.ReplaceAll(filepath.Join(outDir, "wrappers", "bridge.ts"), "\\", "\\\\")

	tsTestScript := fmt.Sprintf(`
const bridge = require("%s");

process.env.GO_ANYTHING_BRIDGE_BIN = "%s";

async function run() {
  const client = bridge.getClient();

  // 1. Normal execution through Go sidecar
  const res1 = await bridge.calculateTax({ amount: 100.0, currency: "USD" });
  console.log("RES1:", res1);
  if (Math.abs(res1.tax_amount - 20.0) > 1e-5 || res1.currency !== "USD") {
    throw new Error("Unexpected res1: " + JSON.stringify(res1));
  }

  // 2. Kill-switch test: GO_ANYTHING_BRIDGE=off should route to fallback
  process.env.GO_ANYTHING_BRIDGE = "off";
  let fallbackInvoked = false;
  // Overwrite _original_calculate_tax via monkeypatch or client
  // In TS wrapper, when GO_ANYTHING_BRIDGE === 'off', it returns _original_calculate_tax(params)
  // which throws "Original fallback implementation of calculate_tax not provided"
  try {
    await bridge.calculateTax({ amount: 100.0, currency: "USD" });
  } catch (err) {
    if (err.message.includes("Original fallback implementation")) {
      fallbackInvoked = true;
    } else {
      throw err;
    }
  }
  if (!fallbackInvoked) {
    throw new Error("Expected fallback to be invoked when GO_ANYTHING_BRIDGE=off");
  }

  // 3. Process crash resilience test
  process.env.GO_ANYTHING_BRIDGE = "on";
  if (client.proc) {
    client.proc.kill();
  }

  // Next call should handle the dead process gracefully
  // (falls back to original or restarts) without hanging or unhandled rejection
  try {
    const res3 = await bridge.calculateTax({ amount: 200.0, currency: "GBP" });
    console.log("RES3:", res3);
  } catch (err) {
    // Both clean error or fallback are valid resilient behaviors
    console.log("Caught expected handled error/fallback:", err.message);
  }

  client.close();
  console.log("TYPESCRIPT_TEST_SUCCESS");
}

run()
  .then(() => {
    process.exit(0);
  })
  .catch((err) => {
    console.error(err);
    process.exit(1);
  });
`, escapedWrapperPath, escapedBinPath)

	tsScriptPath := filepath.Join(wsDir, "test_wrapper.ts")
	require.NoError(t, os.WriteFile(tsScriptPath, []byte(tsTestScript), 0644))

	nodeCmd := exec.Command("node", "--experimental-strip-types", tsScriptPath)
	nodeCmd.Dir = wsDir
	nodeOut, err := nodeCmd.CombinedOutput()
	require.NoError(t, err, "node/typescript wrapper test failed: %s", string(nodeOut))
	assert.Contains(t, string(nodeOut), "TYPESCRIPT_TEST_SUCCESS")
}
